        isAnonymous: isAnon,
        fio: isAnon ? "— (Конфиденциально)" : (appealData.fio || (this.state.currentUser ? this.state.currentUser.name : "Сотрудник")),
        division: appealData.division || (this.state.currentUser ? this.state.currentUser.division : "ОДС"),
